#!/usr/bin/env python3
"""Rebuild Chinese spelling classifiers from maintained, public fixed inputs.

The ordered prism algebra in config/pc/stellae/spelling.yaml is itself a
maintained input. It includes internal channels beyond the classifier tables;
this script never infers or rewrites those rules from generated Lua data.

SPDX-License-Identifier: GPL-3.0-only
"""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import re
import string


ROOT = Path(__file__).resolve().parents[2]
SYLLABLES = ROOT / 'sources/spelling/cn-syllables.txt'
LUNA_SOURCE = ROOT / 'sources/base/luna_pinyin.dict.yaml'
FINAL_SWAPS = {
    'ang': ('zcs', ('nag', 'agn')),
    'ong': ('zc', ('nog', 'ogn')),
    'ui': ('zcs', ('iu',)),
    'ua': ('zs', ('au',)),
    'uai': ('zcs', ('aui',)),
    'uan': ('zcs', ('aun',)),
    'uang': ('zcs', ('aung', 'uagn', 'unag')),
    'ei': ('z', ('ie',)),
}


def ordinary_forms(syllable):
    """Return full spellings, proper prefixes, and bounded legacy errors."""
    normal = re.sub(r'([ei])ng$', r'\1n', syllable)
    aliases = {normal}
    for pattern, replacement in (
        (r'^([nl])ve$', r'\1ue'), (r'^([jqxy])u', r'\1v'),
        (r'^([nl])ue$', r'\1ve'), (r'^([jqxy])v', r'\1u'),
        (r'un$', 'uen'), (r'ui$', 'uei'), (r'iu$', 'iou'),
    ):
        aliases.update(re.sub(pattern, replacement, value) for value in tuple(aliases))
    forms = dict.fromkeys(aliases, 0)
    for alias in aliases:
        for length in range(1, len(alias)):
            forms.setdefault(alias[:length], 1)
    # Snapshot ordinary forms: errors are never fed back into error expansion.
    for value, kind in tuple(forms.items()):
        for position in range(len(value) - 1):
            if value[position] != value[position + 1]:
                swapped = value[:position] + value[position + 1] + value[position] + value[position + 2:]
                forms.setdefault(swapped, 2)
        # A one-letter abbreviation cannot consume an arbitrary second key.
        if len(value) >= 2 or kind == 0:
            for position in range(len(value) + 1):
                for letter in string.ascii_lowercase:
                    forms.setdefault(value[:position] + letter + value[position:], 2)
    return normal, forms


def neighbors():
    """Use quarter-key coordinates for staggered QWERTY adjacency."""
    coordinates = {
        letter: (row, column * 4 + offset)
        for row, (letters, offset) in enumerate((
            ('qwertyuiop', 0), ('asdfghjkl', 1), ('zxcvbnm', 3)))
        for column, letter in enumerate(letters)
    }
    return {
        letter: sorted(other for other, (other_row, other_x) in coordinates.items()
                       if (row == other_row and abs(x - other_x) == 4)
                       or (abs(row - other_row) == 1 and abs(x - other_x) <= 3))
        for letter, (row, x) in coordinates.items()
    }


def extra_forms(normal, ordinary, adjacent):
    """Return independent feature masks: deletion=1, neighbor=2, swaps=4."""
    result = {}

    def add(value, mask):
        if value not in ordinary:
            result[value] = result.get(value, 0) | mask

    for value, kind in ordinary.items():
        if kind >= 2:
            continue
        for position in range(1, len(value) - 1):
            add(value[:position] + value[position + 1:], 1)
        if len(value) >= 2:
            for position, letter in enumerate(value):
                for neighbor in adjacent[letter]:
                    add(value[:position] + neighbor + value[position + 1:], 2)
    for final, replacement in (('uang', 'augn'), ('iong', 'oign')):
        if normal.endswith(final):
            add(normal[:-len(final)] + replacement, 4)
    if normal[:2] in ('zh', 'ch', 'sh'):
        initials, replacements = FINAL_SWAPS.get(normal[2:], ('', ()))
        if normal[0] in initials:
            for replacement in replacements:
                add('h' + normal[0] + replacement, 4)
    return result


def render(syllables):
    base = ['return {']
    extra = ['-- Generated by schemes/scripts/data/rebuild_chinese_spelling.py.',
             '-- Bits: 1=interior deletion, 2=QWERTY neighbor, 4=two swaps.', 'return {']
    adjacent = neighbors()
    base_pairs = extra_pairs = 0
    for syllable in syllables:
        normal, forms = ordinary_forms(syllable)
        values = ','.join('["%s"]=%d' % item for item in sorted(forms.items()))
        base.append('  ["%s"]={max_length=%d,values={%s}},' % (
            syllable, max(map(len, forms)), values))
        base_pairs += len(forms)
        added = extra_forms(normal, forms, adjacent)
        if added:
            values = ','.join('["%s"]=%d' % item for item in sorted(added.items()))
            extra.append('  ["%s"]={%s},' % (syllable, values))
            extra_pairs += len(added)
    outputs = {
        # Preserve the distributed tables' fixed CRLF encoding as well as data.
        'lua/data/cn_forms.lua': ('\r\n'.join(base) + '\r\n}\r\n').encode('utf-8'),
        'lua/data/cn_extra_forms.lua': ('\r\n'.join(extra) + '\r\n}\r\n').encode('utf-8'),
    }
    neighbor_lines = ['-- Generated by schemes/scripts/data/rebuild_chinese_spelling.py.', 'return {']
    neighbor_lines.extend('  %s="%s",' % (letter, ''.join(values))
                          for letter, values in sorted(adjacent.items()))
    outputs['lua/cn/cn_neighbor_keys.lua'] = ('\r\n'.join(neighbor_lines) + '\r\n}\r\n').encode('utf-8')
    return outputs, {'syllables': len(syllables), 'base_pairs': base_pairs, 'extra_pairs': extra_pairs}


def rebuild(profile, check=False):
    syllables = SYLLABLES.read_text(encoding='utf-8').splitlines()
    if syllables != sorted(set(syllables)) or not syllables or any(
            not re.fullmatch('[a-z]+', value) or value == 'xx' for value in syllables):
        raise ValueError('Canonical syllables must be unique, sorted lowercase spellings.')
    source_codes = {
        code for line in LUNA_SOURCE.read_text(encoding='utf-8-sig').splitlines()
        if '\t' in line and not line.startswith('#')
        for code in line.split('\t')[1].split()
        if re.fullmatch('[a-z]+', code) and code != 'xx'
    }
    if set(syllables) != source_codes:
        raise ValueError('Canonical syllables differ from the maintained original Luna source.')
    # These fixed rules also encode exact, reliable, and normal-only channels.
    # They remain an ordered source resource rather than a reverse-engineered
    # by-product of the classifier tables.
    algebra = profile / 'stellae/spelling.yaml'
    rules = [line[4:] for line in algebra.read_text(encoding='utf-8').splitlines()
             if line.startswith('  - ')]
    if not rules or any(not re.match(r'"?(?:derive|erase|fuzz|xform)/', rule) for rule in rules):
        raise ValueError('Unexpected maintained Chinese prism algebra.')
    outputs, report = render(syllables)
    report.update(prism_rules=len(rules), prism_source_sha256=sha256(algebra.read_bytes()).hexdigest(),
                  canonical_source_sha256=sha256(LUNA_SOURCE.read_bytes()).hexdigest(),
                  check=check, outputs={})
    for relative, data in outputs.items():
        path = profile / relative
        if check:
            if not path.is_file() or path.read_bytes() != data:
                raise ValueError('Generated Chinese spelling classifier differs: ' + relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        report['outputs'][relative] = {'bytes': len(data), 'sha256': sha256(data).hexdigest()}
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile', type=Path, default=ROOT / 'config/pc')
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    try:
        result = rebuild(arguments.profile.resolve(), arguments.check)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    print(json.dumps(result, indent=2))
